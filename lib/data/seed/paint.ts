/** Pack-size variant with a per-litre price and pack discount for larger tins. */
const packs = (perLitre: number, sizes = [1, 4, 10, 20]): Variant => ({
  key: "packSize",
  label: "Pack Size",
  display: "chip",
  options: sizes.map((l) => {
    const factor = l >= 20 ? 0.88 : l >= 10 ? 0.92 : l >= 4 ? 0.96 : 1;
    const price = Math.round(perLitre * l * factor);
    return { value: `${l} L`, label: `${l} L`, price, mrp: Math.round(perLitre * l * 1.12) };
  }),
});

